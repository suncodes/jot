import fs from 'node:fs'
import path from 'node:path'
import { expect, test, type Page } from '@playwright/test'
import { agentScript, chunkIds, startFakeLlm, type FakeLlm, type FakeResponder } from '../helpers/fake-llm'
import { selectOption, cleanup, launch, openArchive, shot, type Launched } from './helpers'

// 只使用临时库和本地假模型，验证智能体选择、真实执行、持续引用及历史快照。
let fake: FakeLlm
let launched: Launched
let page: Page
let vaultDir: string
const other: FakeResponder = req => String(req.messages[0]?.content).includes('归类助手')
  ? JSON.stringify({ domain: '生活', tags: [], confidence: 0.95, reason: '' }) : '好'
const script = (...steps: Parameters<typeof agentScript>[0]) => fake.setResponder(agentScript(steps, other))
const assistant = () => page.getByTestId('agent')
const input = () => assistant().getByTestId('agent-input')
function write(rel: string, content: string): void {
  const file = path.join(vaultDir, rel)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content, 'utf8')
}
async function indexed(text: string): Promise<void> {
  await expect.poll(() => page.evaluate(async q => {
    const r = await window.jot.invoke('search:query', { text: q })
    return r.ok ? r.data.total : 0
  }, text), { timeout: 10000 }).toBeGreaterThan(0)
}
async function ask(text: string): Promise<void> {
  await input().fill(text)
  await input().press('Enter')
}
async function done(text: string): Promise<void> {
  await expect(assistant().getByTestId('agent-answer').last()).toContainText(text, { timeout: 20000 })
  await expect(assistant().getByTestId('agent-stop')).toHaveCount(0)
}
async function openDoc(title: string): Promise<void> {
  await page.keyboard.press('Control+o')
  await page.getByTestId('quick-open-input').fill(title)
  await expect(page.getByTestId('quick-open-item').first()).toContainText(title)
  await page.getByTestId('quick-open-input').press('Enter')
  await expect(page.locator('[data-testid="doc-view"]:visible')).toBeVisible()
}
async function reference(command: string, detail: string): Promise<void> {
  await input().fill(command)
  const option = assistant().getByTestId('agent-candidates').getByRole('option')
    .filter({ has: page.locator('small').getByText(detail, { exact: true }) })
  await option.click()
}
async function start(model = true): Promise<void> {
  launched = await launch(model ? { llmBaseUrl: fake.baseUrl } : {})
  page = launched.page
  await page.setViewportSize({ width: 1440, height: 940 })
  vaultDir = path.join(launched.workDir, '助手验证库')
  await page.getByTestId('vault-path').fill(vaultDir)
  await page.getByTestId('vault-use').click()
  await page.getByTestId(model ? 'model-next' : 'model-skip').click()
  await page.getByTestId('onboarding-start').click()
  await page.evaluate(() => window.jot.invoke('settings:set', { classify: { enabled: false }, daily: { enabled: false }, appearance: { theme: 'light' } }))
  // 关闭测试机器上的快捷键占用提示，避免提示条挤压截图中的布局。
  for (const close of await page.getByTestId('toast').locator('button.close').all()) await close.click()
  await page.keyboard.press('Control+l')
  await expect(input()).toBeFocused()
}
