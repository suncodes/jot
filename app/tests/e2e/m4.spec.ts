  await page.getByTestId('theme-toggle').click()
  await shot(page, 'assistant-dark')
  const resize = async (width: number) => {
    const panel = await page.getByTestId('agent-panel').boundingBox()
    const handle = await page.getByTestId('agent-resizer').boundingBox()
    await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + 100)
    await page.mouse.down()
    await page.mouse.move(handle!.x + handle!.width / 2 + panel!.width - width, handle!.y + 100)
    await page.mouse.up()
    await expect.poll(() => page.getByTestId('agent-panel').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(width)
    const resized = (await page.getByTestId('agent-panel').boundingBox())!
    for (const id of ['agent-select', 'agent-mention', 'agent-send']) {
      const control = (await assistant().getByTestId(id).boundingBox())!
      expect(control.x).toBeGreaterThanOrEqual(resized.x)
      expect(control.x + control.width).toBeLessThanOrEqual(resized.x + resized.width)
      expect(control.y + control.height).toBeLessThanOrEqual(resized.y + resized.height)
    }
  }
  await resize(560)
  await shot(page, 'assistant-wide')
  await resize(348)
  await shot(page, 'assistant-narrow')
  expect(await input().evaluate(el => el.scrollWidth <= el.clientWidth + 2)).toBe(true)
  await assistant().getByTestId('agent-close').click()
  // 关闭测试机器上的快捷键占用提示，避免提示条挤压截图中的布局。
  for (const close of await page.getByTestId('toast').locator('button.close').all()) await close.click()
  await page.keyboard.press('Control+l')
  await expect(input()).toBeFocused()
