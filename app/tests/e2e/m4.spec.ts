  await assistant().getByTestId('agent-retry').click()
  await done('重新提问成功')
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text: string) => { (window as unknown as { copiedAnswer: string }).copiedAnswer = text } } }) })
