test('回收站保留恢复；永久删除先确认；清空只删除确认时的条目', async () => {
  await start()
  await page.evaluate(async () => {
    for (const title of ['待删一', '待删二']) {
      const result = await window.jot.invoke('doc:create', { dir: 'notes', title })
      if (!result.ok) throw new Error(result.error.message)
      await window.jot.invoke('doc:delete', { ref: { path: result.data.path } })
    }
  })
  await trash()
  await expect(page.getByTestId('trash-restore')).toHaveCount(2)
  await page.getByTestId('trash-item').first().getByTestId('trash-item-more').click()
  await page.getByTestId('trash-purge').click()
  await expect(page.getByTestId('app-dialog')).toContainText('1 项')
  await cancel()
  await expect(page.getByTestId('trash-item')).toHaveCount(2)
  await page.getByTestId('trash-item').first().getByTestId('trash-item-more').click()
  await page.getByTestId('trash-purge').click()
  await page.getByTestId('trash-purge-confirm').click()
  await expect(page.getByTestId('trash-item')).toHaveCount(1)
  await expect(page.getByTestId('trash-item').getByTestId('trash-restore')).toBeFocused()
  await page.getByTestId('trash-more').click()
  await page.getByTestId('trash-empty-all').click()
  await expect(page.getByTestId('app-dialog')).toContainText('1 项')
  await page.evaluate(async () => {
    const result = await window.jot.invoke('doc:create', { dir: 'notes', title: '确认后新回收' })
    if (!result.ok) throw new Error(result.error.message)
    await window.jot.invoke('doc:delete', { ref: { path: result.data.path } })
  })
  await shot(page, 'object-trash-purge-confirmation')
  await page.getByTestId('trash-purge-confirm').click()
  await expect(page.getByTestId('trash-item')).toHaveCount(1)
  await expect(page.getByTestId('trash-item')).toContainText('确认后新回收')
  await page.getByTestId('trash-restore').click()
  await expect(page.getByTestId('trash-empty')).toBeVisible()
  expect(fs.existsSync(path.join(vault, 'notes/确认后新回收.md'))).toBe(true)
})
