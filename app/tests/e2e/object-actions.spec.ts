import fs from 'node:fs'
import path from 'node:path'
import { expect, test, type Locator, type Page } from '@playwright/test'
import { agentScript, startFakeLlm, type FakeLlm } from '../helpers/fake-llm'
import { cleanup, launch, selectOption, shot, showSide, type Launched } from './helpers'

let fake: FakeLlm
let launched: Launched
let page: Page
let vault: string
const doc = () => page.locator('[data-testid="doc-view"]:visible')
const tree = (p: string) => page.getByTestId('tree-' + p)
const domainRow = (name: string) => page.locator('[data-testid="library-domain"][data-domain=' + JSON.stringify(name) + ']').locator('..')
const projectRow = (name: string) => page.locator('[data-testid="project-row"][data-name=' + JSON.stringify(name) + ']').locator('..')
const activePath = () => page.locator('[data-testid="tab"].active').getAttribute('data-path')
function write(p: string, text: string): void {
  const file = path.join(vault, p)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text)
}
async function start(model = false): Promise<void> {
  launched = await launch(model ? { llmBaseUrl: fake.baseUrl } : {})
  page = launched.page
  vault = path.join(launched.workDir, '对象操作验证库')
  await page.evaluate(() => window.jot.invoke('settings:set', { capture: { hotkey: 'Ctrl+Alt+Shift+F10' } }))
  await page.getByTestId('vault-path').fill(vault)
  await page.getByTestId('vault-use').click()
  await page.getByTestId(model ? 'model-next' : 'model-skip').click()
  await page.getByTestId('onboarding-start').click()
  await expect(page.getByTestId('shell')).toBeVisible()
  await page.evaluate(() => window.jot.invoke('settings:set', { classify: { enabled: false }, daily: { enabled: false } }))
}
async function library(): Promise<void> { await page.getByTestId('ribbon-library').click(); await expect(page.getByTestId('library-view')).toBeVisible() }
async function trash(): Promise<void> {
  if (!(await page.getByTestId('ribbon-trash').isVisible())) await page.getByTestId('tools-open').click()
  await page.getByTestId('ribbon-trash').click()
  await expect(page.getByTestId('trash-view')).toBeVisible()
}
async function folderAction(p: string, action: string): Promise<void> {
  await tree(p).click({ button: 'right' })
  await expect(page.getByTestId('tree-menu')).toBeVisible()
  await page.getByTestId(action).click()
}
async function folderConfirm(): Promise<void> { await page.getByTestId('folder-confirm').click(); await expect(page.getByTestId('app-dialog')).toHaveCount(0) }
async function cancel(): Promise<void> { await page.getByTestId('app-dialog').getByRole('button', { name: '取消', exact: true }).click() }
async function indexed(n: number): Promise<void> {
  await expect.poll(() => page.evaluate(async () => { const r = await window.jot.invoke('library:query', {}); return r.ok ? r.data.total : -1 })).toBe(n)
}
async function menuWithinViewport(menu: Locator): Promise<void> {
  const box = (await menu.boundingBox())!
  const viewport = page.viewportSize()!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.y).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(viewport.width)
  expect(box.y + box.height).toBeLessThanOrEqual(viewport.height)
}

