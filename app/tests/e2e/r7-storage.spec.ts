test('R7 随手记与无目录笔记分开落盘，目录上下文和旧根部内容保持', async ({ jot }) => {
  const { page, call, select, write } = jot
  await page.getByTestId('capture-input').fill('一条长期保留的灵感')
  await page.getByTestId('capture-save').click()
  await expect(page.getByTestId('capture-input')).toHaveValue('')
  const ideas = await call('library:query', { scope: { selection: { kind: 'collection', name: 'ideas' } } })
  expect(ideas.items[0]?.path).toMatch(/^ideas\/\d{4}\/\d{2}\//)
  expect((await call('classify:inbox', {})).total).toBe(0)
  await page.getByTestId('new-note').click()
  const doc = page.locator('[data-testid="doc-view"]:visible')
  await expect(doc).toHaveAttribute('data-path', /^inbox\/\d{4}\/\d{2}\/未命名.md$/)
  expect((await call('classify:inbox', {})).total).toBe(1)
  await doc.getByTestId('editor').locator('.cm-content').fill('待选择目录的普通笔记')
  await page.getByTestId('ribbon-library').click()
  await page.getByTestId('library-pending').click()
  await expect(page.getByTestId('library-item')).toHaveCount(1)
  await expect(page.getByTestId('library-item')).toContainText('未命名')
  await shot(page, 'r7-pending-note-light')
  await select('content/工作')
  await page.getByTestId('new-note').click()
  await expect(doc).toHaveAttribute('data-path', 'content/工作/未命名.md')
  await page.keyboard.press('Control+n')
  await expect(doc).toHaveAttribute('data-path', 'content/工作/未命名 2.md')
  await doc.getByTestId('editor').locator('.cm-content').fill('当前目录的新笔记')
  write('content/已有根部文件.md', '外部内容不自动搬迁')
  await call('vault:refreshIndex', {})
  await page.getByTestId('ribbon-library').click()
  await page.getByTestId('library-all').click()
  await expect(page.getByTestId('library-item')).toHaveCount(5)
  expect((await call('classify:inbox', {})).total).toBe(1)
  await page.getByTestId('ribbon-today').click()
  await page.getByTestId('new-note').click()
  await expect(doc).toHaveAttribute('data-path', /^inbox\/\d{4}\/\d{2}\/未命名 2.md$/)
})

test('R7 导入默认待归档，可选择正式目录，窄窗可操作且摘要和回收分层', async ({ jot }) => {
  const { page, call, select, vault, launched } = jot
  const outside = path.join(launched.workDir, 'R7资料.md'), original = '---\ntags: [原稿]\n---\n虚构附件'
  fs.writeFileSync(outside, original)
  await page.getByTestId('ribbon-library').click()
  await page.getByTestId('library-import').click()
  await expect(page.getByTestId('import-target')).toContainText('待归档')
  await shot(page, 'r7-import-default-light')
  await page.getByTestId('app-dialog').getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByTestId('theme-toggle').click()
  await page.setViewportSize({ width: 980, height: 800 })
  await page.getByTestId('library-import').click()
  await expect(page.getByTestId('import-target')).toContainText('待归档')
  await shot(page, 'r7-import-default-dark-narrow')
  const chooser = page.waitForEvent('filechooser')
  await page.getByTestId('import-choose').click()
  await (await chooser).setFiles(outside)
  await expect(page.getByTestId('library-title')).toHaveText('待处理')
  await expect(page.getByTestId('library-item')).toHaveCount(1)
  const imported = (await call('classify:inbox', {})).items[0]!.doc.path
  expect(imported).toMatch(/^inbox\/\d{4}\/\d{2}\/R7资料.md$/)
  expect(fs.readFileSync(path.join(vault, imported), 'utf8')).toBe(original)
  expect(fs.existsSync(path.join(vault, imported + '.meta.yaml'))).toBe(true)
  await page.setViewportSize({ width: 1440, height: 940 })
  await select('content/工作')
  await page.getByTestId('library-import').click()
  await expect(page.getByTestId('import-target')).toContainText('工作')
  await selectOption(page, 'import-target', 'content/生活')
  const secondChooser = page.waitForEvent('filechooser')
  await page.getByTestId('import-choose').click()
  await (await secondChooser).setFiles(outside)
  await expect(page.getByTestId('library-title')).toHaveText('生活')
  expect(fs.readFileSync(path.join(vault, 'content/生活/R7资料.md'), 'utf8')).toBe(original)
  const summary = 'wiki/sources/2026/11/虚构摘要.md'
  fs.mkdirSync(path.join(vault, 'wiki/sources/2026/11'), { recursive: true })
  fs.writeFileSync(path.join(vault, summary), '---\ntype: source-summary\nsource: ' + imported + '\n---\n可读摘要')
  await call('vault:refreshIndex', {})
  const removed = await call('library:delete', { path: imported, scope: 'entry' })
  await page.getByTestId('tools-open').click()
  await page.getByTestId('ribbon-trash').click()
  await expect(page.getByTestId('trash-item')).toHaveAttribute('data-path', imported)
  await expect(page.getByTestId('trash-item')).toContainText(summary)
  const trashYears = fs.readdirSync(path.join(vault, '.jot/trash'))
  expect(trashYears.every(year => /^\d{4}$/.test(year))).toBe(true)
  await shot(page, 'r7-monthly-trash-dark')
  await page.getByTestId('trash-restore').click()
  await expect(page.getByTestId('trash-item')).toHaveCount(0)
  expect(fs.existsSync(path.join(vault, summary))).toBe(true)
  expect(fs.readFileSync(path.join(vault, imported), 'utf8')).toBe(original)
  const again = await call('library:delete', { path: imported, scope: 'entry' })
  await expect(page.getByTestId('trash-item')).toHaveCount(1)
  await page.getByTestId('trash-item-more').click()
  await page.getByTestId('trash-purge').click()
  await page.getByTestId('trash-purge-confirm').click()
  await expect(page.getByTestId('trash-item')).toHaveCount(0)
  expect(again.trashId).not.toBe(removed.trashId)
  expect((await call('classify:inbox', {})).total).toBe(0)
})

test('R7 拖入明确目录沿用拖放目标，全局拖入默认待归档', async ({ jot }) => {
  const { page, call, vault, launched } = jot
  const outside = path.join(launched.workDir, '拖入资料.txt')
  fs.writeFileSync(outside, '实际磁盘拖入资料')
  await page.getByTestId('ribbon-library').click()
  await expect(page.locator('[data-testid="library-sidebar"] [data-path="content/工作"]')).toBeVisible()
  // 用浏览器的真实文件对象构造拖放，不替换 preload 的磁盘路径获取方法。
  await page.evaluate(() => {
    const picker = document.createElement('input')
    picker.type = 'file'; picker.id = 'r7-native-drop'; picker.hidden = true
    document.body.append(picker)
  })
  await page.locator('#r7-native-drop').setInputFiles(outside)
  const dispatchDrop = async (selector: string) => page.evaluate(target => {
    const transfer = new DataTransfer()
    transfer.items.add(document.querySelector<HTMLInputElement>('#r7-native-drop')!.files![0]!)
    document.querySelector(target)!.dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true, cancelable: true }))
  }, selector)
  await dispatchDrop('[data-testid="library-sidebar"] [data-path="content/工作"]')
  await expect(page.getByTestId('app-dialog')).toHaveCount(0)
  await expect(page.getByTestId('library-title')).toHaveText('工作')
  expect(fs.readFileSync(path.join(vault, 'content/工作/拖入资料.txt'), 'utf8')).toBe('实际磁盘拖入资料')
  await page.getByTestId('library-all').click()
  await dispatchDrop('[data-testid="shell"]')
  await expect(page.getByTestId('import-target')).toContainText('待归档')
  await page.getByTestId('import-choose').click()
  await expect(page.getByTestId('library-title')).toHaveText('待处理')
  const pending = await call('classify:inbox', {})
  expect(pending.items[0]!.doc.path).toMatch(/^inbox\/\d{4}\/\d{2}\/拖入资料.txt$/)
})

