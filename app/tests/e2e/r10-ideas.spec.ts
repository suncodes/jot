const doc = (page: Page) => page.locator('[data-testid="doc-view"]:visible')
const row = (page: Page, rel: string) => page.locator('[data-testid="library-item"][data-path=' + JSON.stringify(rel) + ']')
async function openIdeas(page: Page): Promise<void> {
  await page.getByTestId('ribbon-library').click()
  await page.getByTestId('library-ideas').click()
  await expect(page.getByTestId('library-title')).toHaveText('灵感')
}

