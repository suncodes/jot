test('保存灵感的提示悬浮于右下角，出现、叠加和关闭时不挤动内容与输入框', async ({ jot }) => {
  const { page, call } = jot
  await openIdeas(page)
  await page.keyboard.press('Control+l')
  const input = page.getByTestId('capture-input')
  const toast = page.getByTestId('toast').filter({ hasText: '已保存到灵感' })
  const geometry = () => page.evaluate(() => Object.fromEntries(
    ['side-panel', 'content', 'capture-bar', 'agent-panel', 'statusbar'].map(id => {
      const element = document.querySelector('[data-testid="' + id + '"]') as HTMLElement | null
      if (!element?.getClientRects().length) return [id, null]
      const { x, y, width, height } = element.getBoundingClientRect()
      return [id, { x, y, width, height }]
    }),
  ))
  for (const narrow of [false, true]) {
    if (narrow) {
      await page.getByTestId('theme-toggle').click()
      await page.setViewportSize({ width: 640, height: 800 })
    }
    await input.fill(narrow ? '窄窗的一条灵感' : '界面不应因保存提示跳动')
    const before = await geometry()
    await input.press('Enter')
    await expect(toast).toHaveCount(1)
    await expect(input).toHaveValue('')
    expect(await geometry()).toEqual(before)
    const floating = await toast.evaluate(el => {
      const stack = el.parentElement!
      const { left, right, bottom } = el.getBoundingClientRect()
      const footer = document.querySelector('[data-testid="statusbar"]')!.getBoundingClientRect()
      return { position: getComputedStyle(stack).position, left, right, bottom, footerTop: footer.top, viewport: innerWidth }
    })
    expect(floating.position).toBe('fixed')
    expect(floating.left).toBeGreaterThanOrEqual(0)
    expect(floating.right).toBeLessThanOrEqual(floating.viewport)
    expect(floating.bottom).toBeLessThanOrEqual(floating.footerTop)
    await input.fill(narrow ? '窄窗连续输入仍可操作' : '提示出现时仍能继续输入')
    await input.press('Enter')
    await expect(toast).toHaveCount(2)
    expect(await geometry()).toEqual(before)
    expect((await call('library:query', { scope: { selection: { kind: 'collection', name: 'ideas' } } })).total).toBe(narrow ? 4 : 2)
    await shot(page, narrow ? 'idea-toast-dark-narrow' : 'idea-toast-light')
    await toast.first().getByRole('button', { name: '关闭', exact: true }).click()
    await expect(toast).toHaveCount(1)
    expect(await geometry()).toEqual(before)
    if (narrow) {
      await toast.getByRole('button', { name: '关闭', exact: true }).click()
      await expect(toast).toHaveCount(0)
    } else {
      await expect(toast).toHaveCount(0, { timeout: 8000 })
    }
    expect(await geometry()).toEqual(before)
  }
})
