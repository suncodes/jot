test('失败运行显示实际摘要、配置与状态筛选，详情菜单可打开原对话', async () => {
  await start()
  const runId = await page.evaluate(async () => {
    const created = await window.jot.invoke('agent:create')
    if (!created.ok) throw new Error(created.error.message)
    const sent = await window.jot.invoke('agent:send', { conversationId: created.data.conversationId, text: '检查失败运行的展示' })
    if (!sent.ok) throw new Error(sent.error.message)
    return sent.data.runId
  })
  await expect.poll(() => page.evaluate(async id => {
    const result = await window.jot.invoke('capabilities:runs', {})
    return result.ok ? result.data.items.some(run => run.id === id) : false
  }, runId)).toBe(true)
  await page.getByTestId('cap-tab-runs').click()
  await page.getByTestId('cap-filter-completed').click()
  await expect(page.getByTestId('cap-empty')).toContainText('没有找到匹配项')
  await page.getByTestId('cap-filter-failed').click()
  await expect(page.getByTestId('cap-result-count')).toHaveText('1 条记录')
  await page.getByTestId('cap-row-' + runId).click()
  await expect(page.getByTestId('cap-run-error')).toBeVisible()
  await expect(page.getByTestId('cap-run-summary')).not.toContainText('未记录')
  await expect(page.getByTestId('cap-run-detail')).toContainText('此运行没有生成回答')
  await page.getByTestId('cap-view-config').click()
  await expect(page.getByTestId('cap-run-snapshot')).toHaveAttribute('open', '')
  await expect(page.getByTestId('cap-run-snapshot')).toContainText('通用助手')
  await shot(page, 'agents-module-run-failure')
  await page.getByTestId('cap-detail-more').click()
  await page.getByRole('menuitem', { name: '打开对话', exact: true }).click()
  await expect(page.getByTestId('agent')).toContainText('检查失败运行的展示')
})

