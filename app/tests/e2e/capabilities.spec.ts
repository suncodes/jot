let launched: Launched
let page: Page
let vault: string
async function start(llmBaseUrl?: string): Promise<void> {
  launched = await launch({ llmBaseUrl, isolateHotkey: true })
  page = launched.page
  await page.setViewportSize({ width: 1440, height: 940 })
  vault = path.join(launched.workDir, '智能体验证库')
  await page.getByTestId('vault-path').fill(vault)
  await page.getByTestId('vault-use').click()
  await page.getByTestId(llmBaseUrl ? 'model-next' : 'model-skip').click()
  await page.getByTestId('onboarding-start').click()
  await page.evaluate(() => window.jot.invoke('settings:set', { classify: { enabled: false }, daily: { enabled: false }, appearance: { theme: 'light' } }))
  await page.getByTestId('ribbon-capabilities').click()
  await expect(page.getByTestId('agents-sidebar')).toBeVisible()
}
async function menu(id: string, name: string): Promise<void> {
  await page.getByTestId('cap-more-' + id).click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}
