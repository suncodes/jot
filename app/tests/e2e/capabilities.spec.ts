test('预览并导入技能目录，重启后用 $ 和 / 调用包内文本', async () => {
  const name = 'reading-template'
  const resource = 'references/format.md'
  const excerpt = '模板字段：观察、出处、下一步'
  const fake = await startFakeLlm(agentScript([
    () => ({ toolCall: { name: 'use_skill', arguments: { name, path: resource } } }),
    results => results[0]!,
  ]))
  try {
    await start(fake.baseUrl)
    const source = path.join(launched.workDir, '外部阅读技能')
    const imported = path.join(vault, '.jot/skills', name)
    fs.mkdirSync(path.join(source, 'references'), { recursive: true })
    fs.mkdirSync(path.join(source, 'scripts'), { recursive: true })
    fs.writeFileSync(path.join(source, resource), excerpt)
    fs.writeFileSync(path.join(source, 'scripts/example.txt'), '随包保存的测试文件')
    fs.writeFileSync(path.join(source, 'SKILL.md'), [
      '---', 'name: ' + name, 'description: 根据包内模板整理阅读内容',
      'disable-model-invocation: true', 'allowed-tools: Read', 'required_tools: [read]', '---',
      '# 阅读模板', '读取 references/format.md 并给出这些字段。', '',
    ].join('\n'))
    await launched.app.evaluate(({ dialog }, chosen) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [chosen] })
    }, source)
    await page.getByTestId('cap-tab-skills').click()
    await page.getByTestId('cap-import').click()
    const dialog = page.getByRole('dialog', { name: '阅读模板' })
    await expect(dialog.getByTestId('cap-import-files')).toContainText(resource)
    await expect(dialog.getByTestId('cap-import-warnings')).toContainText('来源平台声明的工具')
    await expect(dialog.getByTestId('cap-import-warnings')).toContainText('scripts')
    await shot(page, 'skill-import-preview')
    expect(fs.existsSync(imported)).toBe(false)
    await dialog.getByRole('button', { name: '取消' }).click()
    await expect(dialog).toHaveCount(0)
    expect(fs.existsSync(imported)).toBe(false)
    await page.getByTestId('cap-import').click()
    await dialog.getByTestId('cap-import-confirm').click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByTestId('cap-detail').getByRole('heading', { name: '阅读模板' })).toBeVisible()
    expect(fs.readFileSync(path.join(imported, resource), 'utf8')).toBe(excerpt)
    expect(fs.readFileSync(path.join(imported, 'scripts/example.txt'), 'utf8')).toContain('随包保存')

    await page.getByTestId('cap-tab-agents').click()
    await page.getByTestId('cap-create').click()
    await page.getByTestId('cap-edit-name').fill('阅读模板助手')
    await page.getByTestId('cap-edit-description').fill('引用实际导入的技能')
    await page.getByTestId('cap-bind-' + name).check()
    await page.getByTestId('cap-edit-save').click()
    await expect(page.getByTestId('app-dialog')).toHaveCount(0)
    const configuration = JSON.parse(fs.readFileSync(path.join(vault, '.jot/assistant.json'), 'utf8'))
    expect(Object.keys(configuration).sort()).toEqual(['agents', 'defaultInstructions', 'disabledAgentIds', 'disabledBundledPluginIds', 'disabledSkillIds', 'disabledToolIds', 'enabledVaultPluginIds', 'taskSkills'])
    const id = configuration.agents.find((agent: { name: string }) => agent.name === '阅读模板助手').id

    await launched.close()
    launched = await launch({ reuse: launched, llmBaseUrl: fake.baseUrl, isolateHotkey: true })
    page = launched.page
    await expect(page.getByTestId('shell')).toBeVisible()
    const agent = page.getByTestId('agent')
    if (!(await agent.isVisible())) await page.keyboard.press('Control+l')
    await selectOption(page, 'agent-select', id)
    const box = agent.getByTestId('agent-input')
    await box.fill('$' + name)
    const skillOption = page.getByRole('option').filter({ hasText: '阅读模板' })
    await expect(skillOption).toBeVisible()
    await skillOption.click()
    await box.fill('$' + name + ' 列出字段')
    for (const [i, symbol] of ['$', '/'].entries()) {
      if (i > 0) await box.fill(symbol + name + ' 列出字段')
      await agent.getByTestId('agent-send').click()
      await expect(agent.getByTestId('agent-answer')).toHaveCount(i + 1)
      await expect(agent.getByTestId('agent-answer').last()).toContainText(excerpt)
    }

    const history = await page.evaluate(async () => {
      const list = await window.jot.invoke('agent:conversations', {})
      if (!list.ok) throw new Error(list.error.message)
      const saved = await window.jot.invoke('agent:get', { conversationId: list.data.items[0]!.conversationId })
      if (!saved.ok) throw new Error(saved.error.message)
      return saved.data.messages.filter(message => message.role === 'assistant')
    })
    expect(history).toHaveLength(2)
    for (const message of history) {
      expect(message.context?.skillIds).toEqual([name])
      expect(message.toolCalls?.[0]).toMatchObject({ name: 'use_skill', ok: true, output: excerpt })
    }
  } finally { await fake.close() }
})

