import fs from 'node:fs'
import path from 'node:path'
import { test, expect, callOnPage } from './file-fixture'
import { launch, selectOption, shot } from './helpers'
import { workDiaryOptions } from '../helpers/app-extension'

const commandId = 'extension:work-diary:today:today'
const row = (page: import('@playwright/test').Page) => page.locator('[data-testid="extension-row"][data-extension="work-diary"]')
const rail = (page: import('@playwright/test').Page) => page.locator('[data-testid="quick-command"][data-command="' + commandId + '"]')

test('W2：真实表单配置自由月路径、日志来源与两类模板，一个入口初始化月份并打开当天草稿', async ({ jot }) => {
  const { page, call, vault } = jot
  await page.getByTestId('ribbon-settings').click()
  await page.getByTestId('settings-nav-extensions').click()
  await page.getByTestId('extensions-tab-bundled').click()
  await row(page).getByTestId('extension-install').click()
  await page.getByTestId('extension-import-confirm').click()
  await row(page).getByTestId('extension-configure').click()
  await page.getByTestId('extension-profile-edit').click()
  await expect(page.getByTestId('work-diary-fields')).toBeVisible()
  await expect(page.getByTestId('profile-save')).toBeDisabled()
  await page.getByTestId('work-root').fill('content/../外部')
  await expect(page.getByTestId('profile-path-error')).toBeVisible()
  await page.getByTestId('work-root').fill('content/研发/W2工作记录')
  await page.getByTestId('work-draft-directory').fill('草稿/{{yyyy}}年/{{MM}}月')
  await page.getByTestId('work-report-directory').fill('提交/{{yyyy}}年-{{MM}}月')
  await page.getByTestId('work-log-directory').fill('content/工程日志')
  await page.getByTestId('profile-filename').fill('{{yyyy}}-{{MM}}-{{dd}} 工作草稿.md')
  await expect(page.getByTestId('profile-target-path')).toContainText('/2、日报/')
  await expect(page.getByTestId('work-draft-month')).toContainText('/草稿/')
  await expect(page.getByTestId('work-report-month')).toContainText('/提交/')
  await page.getByTestId('work-initialize-okr').uncheck()
  await expect(page.getByTestId('okr-template-kind')).toHaveCount(0)
  await page.getByTestId('work-initialize-okr').check()
  await page.getByTestId('okr-template-preview').click()
  await expect(page.getByTestId('okr-template-content')).toContainText('关键结果')
  await page.getByTestId('okr-template-copy').click()
  await page.getByTestId('okr-template-copy-target').fill('templates/W2/OKR.md')
  await page.getByTestId('okr-template-copy-confirm').click()
  await expect(page.getByTestId('okr-template-kind')).toHaveAttribute('data-value', 'user')
  await page.getByTestId('okr-template-path').fill('templates/W2/不存在.md')
  await expect(page.getByTestId('okr-template-error')).toBeVisible()
  await expect(page.getByTestId('profile-save')).toBeDisabled()
  await page.getByTestId('okr-template-path').fill('templates/W2/OKR.md')
  await page.getByTestId('profile-name').fill('W2写今日工作草稿')
  await page.getByTestId('profile-pinned').check()
  await page.getByTestId('shortcut-record').click()
  await page.keyboard.press('Control+Alt+d')
  await expect(page.getByTestId('profile-save')).toBeEnabled()
  expect(fs.existsSync(path.join(vault, 'content/研发/W2工作记录'))).toBe(false)
  await page.getByTestId('work-root').scrollIntoViewIfNeeded()
  await shot(page, 'w2-work-diary-light')
  await call('settings:set', { appearance: { theme: 'dark' } })
  await page.setViewportSize({ width: 760, height: 900 })
  await page.getByTestId('work-report-directory').scrollIntoViewIfNeeded()
  expect(await page.getByTestId('extension-profile-form').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await shot(page, 'w2-work-diary-dark-narrow')
  await page.getByTestId('profile-save').click()
  await expect(page.getByTestId('extension-profile-editor')).toHaveCount(0)
  const profile = (await call('extensions:configuration', undefined)).extensions['work-diary']!.profiles[0]!
  expect(profile.options).toMatchObject({ root: 'content/研发/W2工作记录', draftDirectory: '草稿/{{yyyy}}年/{{MM}}月', reportDirectory: '提交/{{yyyy}}年-{{MM}}月',
    worklogDirectory: 'content/工程日志', okrTemplate: { kind: 'user', path: 'templates/W2/OKR.md' } })
  if (!('root' in profile.options)) throw new Error('工作配置不符')
  const preview = await call('extensions:previewWorkReport', profile.options)
  await page.getByTestId('extension-enable-detail').click()
  await rail(page).getByRole('button').click()
  await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', preview.dailyDraft.path)
  await expect(page.locator('[data-testid="doc-view"]:visible')).toContainText('今日记录')
  for (const directory of preview.directories) expect(fs.statSync(path.join(vault, directory)).isDirectory()).toBe(true)
  expect(fs.readFileSync(path.join(vault, preview.draftOkrPath), 'utf8')).toContain('关键结果')
  expect(fs.readdirSync(path.join(vault, preview.dailyDraft.directory))).toEqual([preview.dailyDraft.filename])
  for (const directory of preview.directories.filter(directory => directory.startsWith(preview.reportDirectory + '/'))) expect(fs.readdirSync(path.join(vault, directory))).toEqual([])
  const original = fs.readFileSync(path.join(vault, preview.dailyDraft.path), 'utf8')
  await rail(page).getByRole('button').click()
  expect(fs.readFileSync(path.join(vault, preview.dailyDraft.path), 'utf8')).toBe(original)
  expect((await call('app:status', undefined)).modelState).toBe('not-configured')
})

test('W2：已有草稿月目录直接跳过其他目录和OKR，重启仍打开原篇，关闭OKR配置可保存', async ({ jot }) => {
  const { page, call, vault, launched } = jot
  const pending = await call('extensions:previewImport', { source: { kind: 'bundled', id: 'work-diary' } })
  await call('extensions:confirmImport', { token: pending!.token })
  const options = workDiaryOptions('content/W2现有目录', { okrTemplate: { kind: 'package', path: 'templates/okr.md' } })
  await call('extensions:saveProfile', { id: 'work-diary', profile: { id: 'today', commandId: 'today', name: 'W2已有月份', options }, shortcut: { pinned: true, hotkey: null } })
  await call('extensions:setEnabled', { id: 'work-diary', enabled: true })
  const preview = await call('extensions:previewWorkReport', options)
  fs.mkdirSync(path.join(vault, preview.draftDirectory), { recursive: true })
  jot.write(preview.reportDirectory, '用户文件，不应因点击日记而检查或改动')
  await rail(page).getByRole('button').click()
  await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', preview.dailyDraft.path)
  expect(fs.existsSync(path.join(vault, preview.draftOkrPath))).toBe(false)
  expect(fs.existsSync(path.join(vault, preview.draftDirectory, '3、周报'))).toBe(false)
  const original = fs.readFileSync(path.join(vault, preview.dailyDraft.path), 'utf8')
  await page.getByTestId('ribbon-settings').click()
  await page.getByTestId('settings-nav-extensions').click()
  await row(page).getByTestId('extension-configure').click()
  await page.getByTestId('extension-profile-edit').click()
  await expect(page.getByTestId('work-root')).toHaveValue(options.root!)
  await page.getByTestId('work-initialize-okr').uncheck()
  await selectOption(page, 'profile-template-kind', 'none')
  await expect(page.getByTestId('profile-save')).toBeEnabled()
  await page.getByTestId('profile-save').click()
  await expect(page.getByTestId('extension-profile-editor')).toHaveCount(0)
  const saved = (await call('extensions:configuration', undefined)).extensions['work-diary']!.profiles[0]!
  expect(saved.options).toMatchObject({ okrTemplate: null, template: { kind: 'none' } })
  await launched.close()
  const restarted = await launch({ isolateHotkey: true, reuse: launched })
  try {
    await expect(rail(restarted.page)).toBeVisible()
    await rail(restarted.page).getByRole('button').click()
    await expect(restarted.page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', preview.dailyDraft.path)
    expect(await callOnPage(restarted.page, 'commands:execute', { id: commandId })).toEqual({ kind: 'open-note', path: preview.dailyDraft.path, created: false })
    expect(fs.readFileSync(path.join(vault, preview.dailyDraft.path), 'utf8')).toBe(original)
    expect(fs.readFileSync(path.join(vault, preview.reportDirectory), 'utf8')).toContain('用户文件')
    expect(fs.existsSync(path.join(vault, preview.draftOkrPath))).toBe(false)
  } finally { await restarted.close() }
})
