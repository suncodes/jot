async function settings(page: Page, section: string): Promise<void> {
  if (!(await page.getByTestId('settings-sidebar').isVisible())) await page.getByTestId('ribbon-settings').click()
  await page.getByTestId('settings-nav-' + section).click()
}
const extension = (page: Page, id: string) => page.locator('[data-testid="extension-row"][data-extension="' + id + '"]')
async function install(page: Page, id: string): Promise<void> {
  await page.getByTestId('extensions-tab-bundled').click()
  await extension(page, id).getByTestId('extension-install').click()
  await expect(page.getByRole('dialog', { name: /^(安装|更新)预览$/ })).toContainText(id)
  await page.getByTestId('extension-import-confirm').click()
  await expect(page.getByRole('dialog', { name: /^(安装|更新)预览$/ })).toHaveCount(0)
  await expect(extension(page, id).getByTestId('extension-toggle')).toHaveAttribute('aria-checked', 'false')
}
async function record(page: Page, key: string): Promise<void> {
  await page.getByTestId('shortcut-record').click()
  await page.keyboard.press(key)
}

