import fs from 'node:fs'
import path from 'node:path'
import { test, expect } from './file-fixture'
import { shot } from './helpers'

test('文件和目录可固定、排序和打开，重载后保留，失效入口仍可取消', async ({ jot }) => {
  const { page, call, write, vault } = jot
  const a = 'content/工作/客户A/规则.md', b = 'content/生活/客户B/规则.md'
  write(a, '业务规则'); write(b, '生活规则')
  await call('vault:refreshIndex', {})
  await page.getByTestId('ribbon-library').click()
  const sidebar = page.getByTestId('library-sidebar')
  await expect(sidebar.getByTestId('library-pins')).toHaveCount(0)
  for (const file of [a, b]) {
    const item = page.getByTestId('library-item').filter({ has: page.locator('[data-testid="library-item-open"]') }).and(page.locator('[data-path=' + JSON.stringify(file) + ']'))
    await item.click({ button: 'right' })
    await page.getByTestId('content-pin').click()
    await expect(sidebar.locator('[data-pin-path=' + JSON.stringify(file) + ']')).toBeVisible()
  }
  const pinned = (file: string) => sidebar.locator('[data-pin-path=' + JSON.stringify(file) + ']')
  await expect(pinned(a)).toContainText('工作/客户A')
  await expect(pinned(b)).toContainText('生活/客户B')
  const folder = sidebar.locator('[data-directory-path="content/工作"]')
  await folder.getByTestId('folder-more').click()
  await page.getByTestId('folder-pin').click()
  await expect(pinned('content/工作')).toBeVisible()
  await pinned('content/工作').getByTestId('pin-more').click()
  await page.getByTestId('pin-up').click()
  await expect.poll(() => sidebar.locator('[data-pin-path]').evaluateAll(rows => rows.map(row => row.getAttribute('data-pin-path')))).toEqual([a, 'content/工作', b])
  await pinned(a).getByTestId('pin-open').click()
  await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', a)
  await pinned('content/工作').getByTestId('pin-open').click()
  await expect(page.getByTestId('library-title')).toHaveText('工作')

  await page.reload()
  await expect(page.getByTestId('shell')).toBeVisible()
  await page.getByTestId('ribbon-library').click()
  await expect(sidebar.locator('[data-pin-path]')).toHaveCount(3)
  await expect(pinned(a).getByTestId('pin-open')).toBeEnabled()
  fs.renameSync(path.join(vault, a), path.join(vault, 'content/工作/客户A/外部改名.md'))
  await call('vault:refreshIndex', {})
  await expect(pinned(a)).toContainText('已失效')
  await expect(pinned(a).getByTestId('pin-open')).toBeDisabled()
  await pinned(a).click({ button: 'right' })
  await page.getByTestId('pin-remove').click()
  await expect(pinned(a)).toHaveCount(0)
  for (const file of ['content/工作', b]) {
    await pinned(file).getByTestId('pin-more').click()
    await page.getByTestId('pin-remove').click()
  }
  await expect(sidebar.getByTestId('library-pins')).toHaveCount(0)
  // 固定配置不可读时，普通文件及目录操作仍可使用。
  write('.jot/library-pins.json', '{损坏的配置')
  await folder.getByTestId('folder-more').click()
  await expect(page.getByTestId('folder-rename')).toBeEnabled()
  await page.keyboard.press('Escape')
  await page.locator('[data-testid="library-item"][data-path=' + JSON.stringify(b) + ']').getByTestId('content-more').click()
  await expect(page.getByTestId('content-rename')).toBeEnabled()
  await page.keyboard.press('Escape')
})

test('全部与分支展开收起分开控制，单层箭头保留，刷新不重新展开', async ({ jot }) => {
  const { page, call, write } = jot
  await page.getByTestId('ribbon-library').click()
  const sidebar = page.getByTestId('library-sidebar')
  const all = sidebar.getByTestId('library-expand-all')
  await expect(all).toBeDisabled()
  write('content/工作/项目A/规则/版本/说明.md', '正文')
  write('content/生活/学习/课程/笔记.md', '正文')
  await call('vault:refreshIndex', {})
  const row = (relative: string) => sidebar.locator('[data-directory-path=' + JSON.stringify(relative) + ']')
  await expect(all).toBeEnabled()
  await all.click()
  await expect(row('content/工作/项目A/规则/版本')).toBeVisible()
  await expect(row('content/生活/学习/课程')).toBeVisible()
  await expect(all).toHaveAttribute('aria-label', '收起全部目录')
  const branch = row('content/工作/项目A').getByTestId('library-branch-toggle')
  await branch.focus()
  await expect(branch).toHaveCSS('opacity', '1')
  await branch.press('Enter')
  await expect(row('content/工作/项目A/规则')).toHaveCount(0)
  await expect(row('content/生活/学习/课程')).toBeVisible()
  await row('content/工作/项目A').getByTestId('library-toggle').click()
  await expect(row('content/工作/项目A/规则')).toBeVisible()
  await expect(row('content/工作/项目A/规则/版本')).toHaveCount(0)
  await expect(all).toHaveAttribute('aria-label', '展开全部目录')
  await all.click()
  await expect(row('content/工作/项目A/规则/版本')).toBeVisible()
  await expect(row('content/工作/项目A/规则/版本').getByTestId('library-branch-toggle')).toHaveCount(0)
  await all.click()
  await expect(row('content/工作/项目A')).toHaveCount(0)
  await call('vault:createFolder', { parent: 'content', name: '刷新后新目录' })
  await expect(row('content/刷新后新目录')).toBeVisible()
  await expect(row('content/工作/项目A')).toHaveCount(0)
  await expect(row('content/生活/学习')).toHaveCount(0)
})

test('定位展开祖先并滚动高亮，保持编辑器和草稿，灵感与待处理定位逻辑入口', async ({ jot }) => {
  const { page, call, write, open, vault } = jot
  const file = 'content/工作/项目A/规则/最新规范与资料说明.md'
  for (let index = 0; index < 35; index++) fs.mkdirSync(path.join(vault, 'content/工作/目录' + String(index).padStart(2, '0')), { recursive: true })
  write(file, '初始正文')
  write('ideas/2026/11/想法.md', '随手想法')
  write('inbox/2026/11/待处理.md', '待处理资料')
  await call('vault:refreshIndex', {})
  await call('library:setPinned', { path: file, kind: 'file', pinned: true })
  await call('library:setPinned', { path: 'content/工作/项目A', kind: 'folder', pinned: true })
  await call('settings:set', { layout: { agentCollapsed: true } })
  await open(file)
  const doc = page.locator('[data-testid="doc-view"]:visible')
  await doc.getByTestId('doc-toggle').click()
  await doc.locator('.cm-content').fill('定位时正在编写的草稿')
  const editor = await doc.locator('.cm-content').elementHandle()
  const sidebar = page.getByTestId('library-sidebar')
  const locate = sidebar.getByTestId('library-locate')
  await expect(locate).toBeEnabled()
  await locate.click()
  const directory = sidebar.locator('[data-directory-path="content/工作/项目A/规则"]')
  await expect(directory).toBeVisible()
  await expect(directory).toHaveClass(/located/)
  await expect(doc).toHaveAttribute('data-path', file)
  await expect(doc.locator('.cm-content')).toHaveText('定位时正在编写的草稿')
  expect(await editor!.evaluate(element => element.isConnected)).toBe(true)
  expect(await sidebar.locator('nav').evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  const box = (await directory.boundingBox())!, nav = (await sidebar.locator('nav').boundingBox())!
  expect(box.y).toBeGreaterThanOrEqual(nav.y)
  expect(box.y + box.height).toBeLessThanOrEqual(nav.y + nav.height + 1)
  expect(await page.getByTestId('side-panel').evaluate(element => element.getBoundingClientRect().width)).toBe(224)
  await sidebar.locator('nav').evaluate(element => { element.scrollTop = 0 })
  await shot(page, 'library-navigation-light')
  await page.getByTestId('theme-toggle').click()
  await shot(page, 'library-navigation-dark')
  await page.setViewportSize({ width: 980, height: 800 })
  await shot(page, 'library-navigation-narrow')
  expect(await sidebar.locator('nav').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.getByTestId('side-panel').evaluate(element => element.getBoundingClientRect().width)).toBe(224)

  await open('ideas/2026/11/想法.md')
  await locate.click()
  await expect(sidebar.getByTestId('library-ideas')).toHaveClass(/located/)
  await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', 'ideas/2026/11/想法.md')
  await open('inbox/2026/11/待处理.md')
  await locate.click()
  await expect(sidebar.getByTestId('library-pending')).toHaveClass(/located/)
  await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', 'inbox/2026/11/待处理.md')
  await sidebar.getByTestId('library-all').click()
  await expect(locate).toBeDisabled()
})
