    await page.getByTestId('storage-maintenance').scrollIntoViewIfNeeded()
    await expect(page.getByTestId('storage-conversations-count')).toHaveText('2 个已保存对话 · 2 条消息')
    await page.getByTestId('storage-history').click()
    await expect(page.getByTestId('agent-history-list')).toBeVisible()
    const conversation = page.getByTestId('agent-conversation').filter({ hasText: '核对实际会话删除入口' })
    await conversation.getByTestId('conversation-more').click()
    await page.getByTestId('agent-conversation-delete').click()
    const confirmation = page.getByTestId('app-dialog').filter({ hasText: '无法恢复' })
    await confirmation.getByRole('button', { name: '取消', exact: true }).click()
    expect((await call('agent:conversations', {})).total).toBe(2)
    await conversation.getByTestId('conversation-more').click()
