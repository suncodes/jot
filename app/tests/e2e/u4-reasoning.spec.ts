test('直接选择跨重启恢复，显示实际档位并继承模型配置；切模型清除覆盖并刷新可选档位', async ({ jot }) => {
  const { page, call, launched } = jot
  const fake = await startFakeLlm(agentScript([() => '本轮完成']))
  let resumed: Awaited<ReturnType<typeof launch>> | undefined
  try {
    await call('settings:set', { ...modelSettings({ baseUrl: fake.baseUrl, model: 'first', apiKey: 'fake', reasoningEffort: 'high' }, await call('settings:get', undefined)) })
    await page.keyboard.press('Control+l')
    await expect(page.getByTestId('agent-reasoning-effort')).toHaveText('高')
    await selectOption(page, 'agent-reasoning-effort', 'low')
    await expect(page.getByTestId('agent-reasoning-effort')).toHaveText('低')
    await page.getByTestId('agent-input').fill('保存本对话选择')
    await page.getByTestId('agent-send').click()
    await expect(page.getByTestId('agent-stop')).toHaveCount(0)
    await expect(page.getByTestId('agent-answer').last()).toContainText('本轮完成')
    await launched.close()
    resumed = await launch({ reuse: launched, isolateHotkey: true })
    const next = resumed.page
    await expect(next.getByTestId('shell')).toBeVisible()
    if (!(await next.getByTestId('agent-input').isVisible())) await next.keyboard.press('Control+l')
    await next.getByTestId('agent-history').click()
    await next.getByTestId('agent-conversation').first().locator('.history-main').click()
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveText('低')
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveAttribute('data-value', 'low')
    await selectOption(next, 'agent-reasoning-effort', 'high')
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveText('高')
    await callOnPage(next, 'settings:set', { ...modelSettings({ reasoningEffort: 'low' }, await callOnPage(next, 'settings:get', undefined)) })
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveText('低')
    const conversationId = (await callOnPage(next, 'agent:conversations', {})).items[0]!.conversationId
    await expect.poll(async () => (await callOnPage(next, 'agent:get', { conversationId })).context?.reasoningEffort).toBeUndefined()
    await next.getByTestId('agent-input').fill('跟随全局')
    await next.getByTestId('agent-send').click()
    await expect(next.getByTestId('agent-answer')).toHaveCount(2)
    await expect(next.getByTestId('agent-stop')).toHaveCount(0)
    expect(fake.requests.filter(isAgentRequest).at(-1)?.reasoning_effort).toBe('low')
    await selectOption(next, 'agent-reasoning-effort', 'medium')
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveText('中')
    await callOnPage(next, 'settings:set', { ...modelSettings({ model: 'second' }, await callOnPage(next, 'settings:get', undefined)) })
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveText('不指定')
    await expect(next.getByTestId('agent-reasoning-effort')).toHaveAttribute('data-value', 'auto')
    expect(defaultModel((await callOnPage(next, 'settings:get', undefined))).reasoningEffort).toBe('auto')
    await callOnPage(next, 'settings:set', { ...modelSettings({ baseUrl: 'https://api.openai.com/v1', model: 'gpt-5.4' }, await callOnPage(next, 'settings:get', undefined)) })
    await next.getByTestId('agent-reasoning-effort').click()
    await expect(next.getByTestId('agent-reasoning-options').getByRole('button', { name: '默认', exact: true })).toHaveCount(0)
    await expect(next.getByTestId('agent-reasoning-options').locator('[data-value="auto"]')).toHaveCount(1)
    await expect(next.getByTestId('agent-reasoning-options').locator('[data-value="off"]')).toBeVisible()
    await expect(next.getByTestId('agent-reasoning-options').locator('[data-value="xhigh"]')).toBeVisible()
    await expect(next.getByTestId('agent-reasoning-options').locator('[data-value="max"]')).toHaveCount(0)
    await next.keyboard.press('Escape')
  } finally { await resumed?.close(); await fake.close() }
})

test('日总结复用现有生成入口，后台详情展示实际技能、模型和请求档位', async ({ jot }) => {
  const { page, call } = jot
  const fake = await startFakeLlm(() => JSON.stringify({ oneLine: '你完成了明确记录的测试', done: ['完成测试'], highlights: [], followUps: [] }))
  try {
    await call('settings:set', { ...modelSettings({ baseUrl: fake.baseUrl, model: 'daily-model', apiKey: 'fake', reasoningEffort: 'medium' }, await call('settings:get', undefined)) })
    const date = localDay(new Date())
    await call('capture:save', { text: '今天明确完成了功能测试', source: 'main-window' })
    const { jobId } = await call('timeline:generateDaily', { date })
    await expect.poll(async () => (await call('jobs:list', { state: 'done' })).items.some(item => item.jobId === jobId)).toBe(true)
    const job = (await call('jobs:list', { state: 'done' })).items.find(item => item.jobId === jobId)!
    expect(job.execution).toMatchObject({ skillId: 'jot-core:daily-review', model: 'daily-model', reasoning: { requested: 'medium', source: 'global' } })
    expect(fake.requests).toHaveLength(1)
    expect(fake.requests[0]?.reasoning_effort).toBe('medium')
    expect((await call('timeline:day', { date })).daily?.body).toContain('你完成了明确记录的测试')
    await page.getByTestId('jobs-open').click()
    await page.getByTestId('jobs-filter').filter({ hasText: '近期完成' }).click()
    await page.getByTestId('job-execution').locator('summary').click()
    await expect(page.getByTestId('job-execution')).toContainText('jot-core:daily-review')
    await expect(page.getByTestId('reasoning-details')).toContainText('全局设置')
    await shot(page, 'u4-daily-task-details')
  } finally { await fake.close() }
})
