import fs from 'node:fs'
import path from 'node:path'
import { test, expect } from './file-fixture'
import { fillTime, selectOption, shot, showSide } from './helpers'
test('多摘要可选择，编辑属性只写原件 sidecar，来源不显示历史版本警告', async ({ jot }) => {
  const { page, call, write, open, vault } = jot
  write('content/工作/资料.txt', '原文')
  write('wiki/sources/摘要甲.md', '---\ntype: source-summary\nsource: content/工作/资料.txt\n---\n第一份摘要')
  write('wiki/sources/摘要乙.md', '---\ntype: source-summary\nsource: content/工作/资料.txt\n---\n第二份摘要')
  await call('vault:refreshIndex', {})
  await open('content/工作/资料.txt')
  const view = page.locator('[data-testid="file-view"]:visible')
  await expect(view.getByTestId('file-summary-select')).toBeVisible()
  await view.getByTestId('file-summary-select').click()
  await page.getByTestId('select-options').locator('[data-value="wiki/sources/摘要乙.md"]').click()
  await expect(view.getByTestId('doc-preview')).toContainText('第二份摘要')
  await view.getByTestId('doc-preview').click()
  await view.getByTestId('editor').locator('.cm-content').fill('第二份摘要（人工修订）')
  await view.getByTestId('file-summary-select').click()
  await page.getByTestId('select-options').locator('[data-value="wiki/sources/摘要甲.md"]').click()
  await expect.poll(() => fs.readFileSync(path.join(vault, 'wiki/sources/摘要乙.md'), 'utf8')).toContain('第二份摘要（人工修订）')
  await expect(view.getByTestId('editor').locator('.cm-content')).toContainText('第一份摘要')
  await view.getByTestId('doc-toggle').click()
  const props = view.getByTestId('props')
  const disclosure = view.getByTestId('props-summary')
  await expect(disclosure).toHaveAttribute('aria-expanded', 'false')
  await disclosure.press('Enter')
  const classification = props.getByRole('region', { name: '分类', exact: true })
  const position = props.getByRole('region', { name: '位置与时间' })
  await expect(classification).toBeVisible()
  await expect(position.getByRole('button', { name: '工作', exact: true })).toHaveAttribute('title', 'content/工作/资料.txt')
  await position.getByTestId('props-move').click()
  await selectOption(page, 'props-move-target', 'content/生活')
  await position.getByTestId('props-move').click()
  await expect(position.getByTestId('props-move-target')).toHaveCount(0)

  const tagInput = classification.getByLabel('标签', { exact: true })
  await tagInput.fill('业务')
  await tagInput.press('Enter')
  await expect(classification.getByTestId('props-tags').getByTestId('chip')).toHaveText('业务')
  const date = position.getByTestId('props-occurred')
  await expect(date).toHaveAccessibleName('发生日期')
  await date.fill('2026-11-19')
  await expect(disclosure).toHaveAttribute('title', /2026-11-19/)
  const place = classification.getByLabel('地点', { exact: true })
  await place.fill('一楼会议室')
  await call('doc:patchProperties', { path: 'content/工作/资料.txt', patch: { occurred_at: '2026-11-20' } })
  await expect(disclosure).toHaveAttribute('title', /2026-11-20/)
  await expect(place).toHaveValue('一楼会议室')
  await place.press('Tab')
  await expect(disclosure).toHaveAttribute('title', /一楼会议室/)
  const people = classification.getByLabel('人物', { exact: true })
  await people.fill('王宁')
  await people.press('Enter')
  await expect(disclosure).toHaveAttribute('title', /@王宁/)
  await expect(view.getByTestId('source-changed')).toHaveCount(0)
  if (await page.locator('html').getAttribute('data-theme') === 'dark') await page.getByTestId('theme-toggle').click()
  await shot(page, 'file-properties-light')

  await disclosure.click()
  await expect(props.getByTestId('props-form')).toHaveCount(0)
  await expect(disclosure).toHaveAttribute('title', /2026-11-20/)
  await shot(page, 'file-properties-collapsed')
  await page.setViewportSize({ width: 980, height: 800 })
  await page.getByTestId('theme-toggle').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await disclosure.click()
  const classificationBox = (await classification.boundingBox())!
  const positionBox = (await position.boundingBox())!
  expect(positionBox.y).toBeGreaterThanOrEqual(classificationBox.y + classificationBox.height)
  expect(await props.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await props.evaluate(el => el.scrollIntoView({ block: 'center' }))
  await shot(page, 'file-properties-dark-narrow')

  await position.getByTestId('props-move').click()
  await selectOption(page, 'props-move-target', 'content/生活')
  await position.getByTestId('props-move-save').click()
  const moved = 'content/生活/资料.txt'
  await expect(view).toHaveAttribute('data-path', moved)
  const updated = await call('doc:get', { ref: { path: moved } })
  expect(updated).toMatchObject({ occurredAt: '2026-11-20', classification: { tags: ['业务'], people: ['王宁'], place: '一楼会议室' } })
  expect(fs.readFileSync(path.join(vault, moved), 'utf8')).toBe('原文')
  expect(fs.readFileSync(path.join(vault, moved + '.meta.yaml'), 'utf8')).toContain('一楼会议室')
})
test('时间线只标文件更新，日总结普通来源可点击，重做需明确确认', async ({ jot }) => {
  const { page, call, write, vault } = jot
  const date = await page.getByTestId('today-view').getAttribute('data-date')
  write('content/工作/业务规则.md', '---\ncreated: ' + date + '\n---\n许多历史成果')
  await call('vault:refreshIndex', {})
  await expect(page.getByTestId('today-entry')).toContainText('具体变化未确认')
  await page.getByTestId('daily-generate').click()
  await expect(page.getByTestId('daily-body')).toContainText('具体变化未确认')
  expect(fs.readFileSync(path.join(vault, 'journal', date!.slice(0, 4), date + '.md'), 'utf8')).toContain('## 来源')
  await expect(page.getByTestId('daily-evidence')).toHaveCount(0)
  await page.getByTestId('daily-regenerate').click()
  await expect(page.getByTestId('toast')).toContainText('覆盖')
  await shot(page, 'r2-timeline-daily')
  await page.getByTestId('daily-open').click()
  const doc = page.locator('[data-testid="doc-view"]:visible')
  await doc.getByTestId('doc-preview').getByRole('link', { name: '业务规则', exact: true }).last().click()
  await expect(doc).toHaveAttribute('data-path', 'content/工作/业务规则.md')
})
test('待处理按inbox物理位置展示资料，修改入口打开原件属性', async ({ jot }) => {
  const { page, call, write, vault } = jot
  write('inbox/待整理.txt', '原件')
  write('wiki/sources/待整理摘要.md', '---\ntype: source-summary\nsource: inbox/待整理.txt\n---\n摘要正文')
  await call('vault:refreshIndex', {})
  await call('doc:patchProperties', { path: 'inbox/待整理.txt', patch: { tags: ['已有标签'] } })
  await showSide(page, 'inbox')
  await expect(page.getByTestId('inbox-item')).toHaveAttribute('data-path', 'inbox/待整理.txt')
  await expect(page.getByTestId('inbox-item')).toContainText('摘要正文')
  await page.getByTestId('inbox-edit').click()
  const view = page.locator('[data-testid="file-view"]:visible')
  await expect(view.getByTestId('props-form')).toBeVisible()
  await view.getByTestId('props-tags-input').fill('人工补充')
  await view.getByTestId('props-tags-input').press('Enter')
  await expect.poll(() => fs.readFileSync(path.join(vault, 'inbox/待整理.txt.meta.yaml'), 'utf8')).toContain('人工补充')
  expect(fs.readFileSync(path.join(vault, 'inbox/待整理.txt'), 'utf8')).toBe('原件')
})

test('补记弹窗支持显式关闭，保存后可在详情属性修改发生时间', async ({ jot }) => {
  const { page, call, open } = jot
  const add = page.getByTestId('today-add-log')
  const dialog = page.getByRole('dialog', { name: '补记一件事' })
  await add.click()
  const input = dialog.getByTestId('log-text')
  await expect(input).toBeFocused()
  await input.fill('未保存的补记')
  const bounds = (await dialog.boundingBox())!
  await page.mouse.click(bounds.x - 20, bounds.y + bounds.height / 2)
  await expect(input).toHaveValue('未保存的补记')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(add).toBeFocused()

  await add.click()
  await fillTime(page, 'log-start', '09:30')
  await fillTime(page, 'log-end', '10:15')
  await input.fill('完成弹窗定向验证')
  await shot(page, 'log-dialog-light')
  await dialog.getByTestId('log-save').click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByTestId('today-entry')).toContainText('完成弹窗定向验证')

  const entry = (await call('library:query', { kind: 'record' })).items[0]!
  await open(entry.path)
  const doc = page.locator('[data-testid="doc-view"]:visible')
  await doc.getByTestId('props-summary').click()
  const section = doc.getByRole('region', { name: '位置与时间' })
  await expect(section.getByTestId('log-time-value')).toContainText('09:30 — 10:15')
  await expect(doc.getByTestId('log-edit-time')).toHaveCount(1)
  await section.getByTestId('log-edit-time').click()
  const timeDialog = page.getByRole('dialog', { name: '修改发生时间' })
  await expect(timeDialog.getByTestId('log-edit-start-time')).toHaveAttribute('data-value', '09:30')
  await fillTime(page, 'log-edit-end-time', '11:00')
  await timeDialog.getByTestId('log-time-save').click()
  await expect(timeDialog).toHaveCount(0)
  await expect(section.getByTestId('log-time-value')).toContainText('09:30 — 11:00')
  const updated = await call('doc:get', { ref: { path: entry.path } })
  expect(updated.created).toBe(entry.created)
  expect(updated.end?.slice(11, 16)).toBe('11:00')
  await shot(page, 'log-properties-time')
})
