test('浅紫色禁用主按钮保留不可提交语义，输入内容后恢复主色描边', async () => {
  await page.keyboard.press('Control+l')
  const capture = page.getByTestId('capture-save')
  const send = page.getByTestId('agent-send')
  for (const theme of ['light', 'dark']) {
    if (await page.locator('html').getAttribute('data-theme') !== theme) await page.getByTestId('theme-toggle').click()
    for (const button of [capture, send]) {
      await expect(button).toBeDisabled()
      await expect(button).toHaveCSS('color', theme === 'light' ? 'rgb(166, 160, 235)' : 'rgb(129, 123, 169)')
      await expect(button).toHaveCSS('border-top-color', theme === 'light' ? 'rgb(211, 207, 245)' : 'rgb(80, 75, 107)')
    }
    await shot(page, 'buttons-disabled-' + theme)
  }
  await page.getByTestId('capture-input').fill('可保存的内容')
  await page.getByTestId('agent-input').fill('可发送的提问')
  for (const button of [capture, send]) {
    await expect(button).toBeEnabled()
    await expect(button).toHaveCSS('color', 'rgb(180, 172, 255)')
    await expect(button).toHaveCSS('border-top-color', 'rgb(180, 172, 255)')
  }
})

