import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { _electron as electron, expect, test, type Page } from '@playwright/test'
import { callOnPage } from '../e2e/file-fixture'
import { shot, windowByUrl } from '../e2e/helpers'

const work = 'extension:work-diary:today:today', personal = 'extension:personal-diary:today:today'
const rail = (page: Page, id: string) => page.locator('[data-testid="quick-command"][data-command="' + id + '"]')
const row = (page: Page, id: string) => page.locator('[data-testid="extension-row"][data-extension="' + id + '"]')
const hash = (file: string) => createHash('sha256').update(fs.readFileSync(file)).digest('hex')
async function extensions(page: Page): Promise<void> {
  if (!(await page.getByTestId('settings-sidebar').isVisible())) await page.getByTestId('ribbon-settings').click()
  await page.getByTestId('settings-nav-extensions').click()
  if (await page.getByTestId('extensions-back').isVisible()) await page.getByTestId('extensions-back').click()
}
async function install(page: Page, id: string): Promise<void> {
  await extensions(page)
  await page.getByTestId('extensions-tab-bundled').click()
  await row(page, id).getByTestId('extension-install').click()
  await expect(page.getByRole('dialog', { name: '安装预览' })).toContainText(id)
  await page.getByTestId('extension-import-confirm').click()
  await expect(row(page, id).getByTestId('extension-toggle')).toHaveAttribute('aria-checked', 'false')
  await row(page, id).getByTestId('extension-configure').click()
  await page.getByTestId('extension-profile-edit').click()
  await page.getByTestId('profile-name').fill(id === 'work-diary' ? 'X6发布工作日记' : 'X6发布个人日记')
  if (id === 'work-diary') await page.getByTestId('work-root').fill('content/工作/X6发布/' + id)
  else await page.getByTestId('profile-directory').fill('content/工作/X6发布/' + id + '/{{yyyy}}年/{{MM}}月')
  if (id === 'work-diary') {
    await page.getByTestId('profile-template-copy').click()
    await page.getByTestId('template-copy-target').fill('templates/X6发布/工作日记.md')
    await page.getByTestId('template-copy-confirm').click()
    await expect(page.getByTestId('profile-template-kind')).toHaveAttribute('data-value', 'user')
  }
  await page.getByTestId('profile-pinned').check()
  await page.getByTestId('shortcut-record').click()
  await page.keyboard.press(id === 'work-diary' ? 'Control+Alt+d' : 'Control+Alt+i')
  await expect(page.getByTestId('profile-save')).toBeEnabled()
  await page.getByTestId('profile-save').click()
  await expect(page.getByTestId('extension-profile-editor')).toHaveCount(0)
  await page.getByTestId('extension-enable-detail').click()
  await expect(rail(page, 'extension:' + id + ':today:today')).toBeVisible()
}

test('X6发布包：独立资源、真实设置安装、三入口同篇、启停及删索引重启，卸载保留原件', async () => {
  const exe = path.resolve(process.env.JOT_PACKED_EXE ?? path.join(import.meta.dirname, '../../dist/win-unpacked/Jot.exe'))
  expect(fs.statSync(exe).isFile()).toBe(true)
  const resources = path.join(path.dirname(exe), 'resources/app-extensions')
  expect(fs.readdirSync(resources).sort()).toEqual(['personal-diary', 'work-diary'])
  for (const id of ['personal-diary', 'work-diary']) {
    const manifest = JSON.parse(fs.readFileSync(path.join(resources, id, 'extension.json'), 'utf8'))
    expect(manifest.id).toBe(id)
    expect(manifest.commands).toHaveLength(1)
    expect(id === 'work-diary' ? manifest.commands[0].defaults.root : manifest.commands[0].defaults.directory).toBeNull()
    for (const name of ['extension.json', 'templates/default.md'])
      expect(hash(path.join(resources, id, name))).toBe(hash(path.resolve(import.meta.dirname, '../../resources/app-extensions', id, name)))
  }
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jot-x6-release-'))
  const vault = path.join(root, 'X6虚构发布库'), data = path.join(root, 'data')
  const env: Record<string, string> = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !entry[0].startsWith('JOT_')))
  Object.assign(env, { JOT_USER_DATA: data, JOT_NO_DOTENV: '1', JOT_TEST_NOW: new Date(2026, 10, 23, 12).toISOString() })
  let app = await electron.launch({ executablePath: exe, env })
  try {
    await app.evaluate(({ globalShortcut }) => { globalShortcut.unregisterAll(); globalShortcut.register = () => true })
    expect(await app.evaluate(({ app }) => app.isPackaged)).toBe(true)
    let page = await windowByUrl(app, 'index.html')
    await page.getByTestId('vault-path').fill(vault)
    await page.getByTestId('vault-use').click()
    await expect(page.getByTestId('dev-model')).toHaveCount(0)
    await page.getByTestId('model-skip').click()
    await page.getByTestId('onboarding-start').click()
    await expect(page.getByTestId('shell')).toBeVisible()
    await page.setViewportSize({ width: 1440, height: 940 })
    await callOnPage(page, 'settings:set', { classify: { enabled: false }, daily: { enabled: false } })
    expect((await callOnPage(page, 'app:info', undefined)).dev).toBe(false)
    expect((await callOnPage(page, 'app:status', undefined)).modelState).toBe('not-configured')
    await expect(page.getByTestId('quick-rail')).toHaveCount(0)
    expect((await callOnPage(page, 'extensions:catalog', undefined)).installed).toHaveLength(0)
    await install(page, 'work-diary')
    expect(fs.existsSync(path.join(vault, '.jot/app-extensions/personal-diary'))).toBe(false)
    await install(page, 'personal-diary')
    await rail(page, work).getByRole('button').click()
    const profile = (await callOnPage(page, 'extensions:configuration', undefined)).extensions['work-diary']!.profiles[0]!
    if (!('root' in profile.options)) throw new Error('工作日记配置不符')
    const target = (await callOnPage(page, 'extensions:previewWorkReport', profile.options)).dailyDraft.path
    await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', target)
    const editor = page.locator('[data-testid="doc-view"]:visible .cm-content')
    await editor.fill('X6发布中手动保存的工作日记。')
    await editor.press('Control+e')
    await expect.poll(() => fs.readFileSync(path.join(vault, target), 'utf8')).toContain('X6发布中手动保存的工作日记。')
    const original = fs.readFileSync(path.join(vault, target), 'utf8')
    await page.keyboard.press('Control+Shift+p')
    await page.getByTestId('command-search').fill('X6发布工作日记')
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('command-palette')).toHaveCount(0)
    await page.getByTestId('capture-input').focus()
    await page.keyboard.press('Control+Alt+d')
    await expect(page.locator('[data-testid="tab"][data-path="' + target + '"]')).toHaveCount(1)
    expect(fs.readFileSync(path.join(vault, target), 'utf8')).toBe(original)
    await rail(page, personal).getByRole('button').click()
    const personalResult = await callOnPage(page, 'commands:execute', { id: personal })
    if (personalResult.kind !== 'open-note') throw new Error('结果不符')
    expect(fs.readFileSync(path.join(vault, personalResult.path), 'utf8')).toContain('一个小收获')
    const template = path.join(vault, 'templates/X6发布/工作日记.md'), templateText = fs.readFileSync(template, 'utf8')
    expect(templateText).toContain('{{title}}')
    await extensions(page)
    await row(page, 'work-diary').getByTestId('extension-toggle').click()
    await expect(rail(page, work)).toHaveCount(0)
    await page.keyboard.press('Control+Shift+p')
    await expect(page.locator('[data-testid="palette-command"][data-command="' + work + '"]')).toHaveCount(0)
    await page.keyboard.press('Escape')
    await row(page, 'work-diary').getByTestId('extension-toggle').click()
    await expect(rail(page, work)).toBeVisible()
    const shortcuts = fs.readFileSync(path.join(vault, '.jot/shortcuts.json'), 'utf8')
    await callOnPage(page, 'vault:rebuildIndex', undefined)
    await page.getByTestId('settings-back').click()
    await page.getByTestId('side-toggle').click()
    await expect(page.getByTestId('quick-rail')).toBeVisible()
    await callOnPage(page, 'settings:set', { appearance: { theme: 'dark' } })
    await page.setViewportSize({ width: 740, height: 820 })
    await page.getByTestId('quick-palette').click()
    await page.getByTestId('command-search').fill('日记')
    await shot(page, 'x6-release-' + (process.env.JOT_PACKED_LABEL ?? 'dist') + '-dark')
    await page.keyboard.press('Escape')
    await app.evaluate(({ app }) => app.exit(0)); await app.close()
    for (const suffix of ['', '-wal', '-shm']) {
      const file = path.join(vault, '.jot/index.db' + suffix)
      if (fs.existsSync(file)) fs.unlinkSync(file)
    }
    app = await electron.launch({ executablePath: exe, env })
    await app.evaluate(({ globalShortcut }) => { globalShortcut.unregisterAll(); globalShortcut.register = () => true })
    page = await windowByUrl(app, 'index.html')
    await expect(rail(page, work)).toBeVisible()
    await expect(rail(page, personal)).toBeVisible()
    expect(fs.readFileSync(path.join(vault, '.jot/shortcuts.json'), 'utf8')).toBe(shortcuts)
    await rail(page, work).getByRole('button').click()
    await expect(page.locator('[data-testid="doc-view"]:visible')).toHaveAttribute('data-path', target)
    expect(fs.readFileSync(path.join(vault, target), 'utf8')).toBe(original)
    await callOnPage(page, 'extensions:uninstall', { id: 'work-diary', confirmed: true })
    await expect(rail(page, work)).toHaveCount(0)
    await expect(rail(page, personal)).toBeVisible()
    expect(fs.readFileSync(template, 'utf8')).toBe(templateText)
    expect(fs.readFileSync(path.join(vault, target), 'utf8')).toBe(original)
    expect(fs.readFileSync(path.join(vault, personalResult.path), 'utf8')).toContain('一个小收获')
    expect((await callOnPage(page, 'app:status', undefined)).modelState).toBe('not-configured')
  } finally {
    await app.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await app.close().catch(() => {})
    await fs.promises.rm(root, { recursive: true, force: true })
  }
})
